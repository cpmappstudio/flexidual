import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const DEFAULT_LOCALE = "en";
const REPO_ROOT = process.cwd();
const MESSAGES_ROOT = path.join(REPO_ROOT, "messages");
const SOURCE_ROOT = path.join(MESSAGES_ROOT, DEFAULT_LOCALE);
const OUTPUT_FILE = path.join(REPO_ROOT, "i18n", "messages.generated.ts");

async function collectJsonFiles(directoryPath) {
  const entries = await readdir(directoryPath, { withFileTypes: true });
  const nestedFiles = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(directoryPath, entry.name);

      if (entry.isDirectory()) {
        return await collectJsonFiles(entryPath);
      }

      if (entry.isFile() && entry.name.endsWith(".json")) {
        return [entryPath];
      }

      return [];
    }),
  );

  return nestedFiles.flat().sort();
}

function toImportIdentifier(filePath) {
  const relativePath = path.relative(SOURCE_ROOT, filePath).replace(/\.json$/, "");
  const segments = relativePath
    .split(path.sep)
    .flatMap((segment) => segment.split(/[^a-zA-Z0-9]/))
    .filter(Boolean);

  return segments
    .map((segment, index) =>
      index === 0
        ? segment.charAt(0).toLowerCase() + segment.slice(1)
        : segment.charAt(0).toUpperCase() + segment.slice(1),
    )
    .join("");
}

async function validateFile(filePath, knownNamespaces) {
  const rawFile = await readFile(filePath, "utf8");
  const parsed = JSON.parse(rawFile);

  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error(`Message file must export an object: ${filePath}`);
  }

  for (const namespace of Object.keys(parsed)) {
    const existingFile = knownNamespaces.get(namespace);
    if (existingFile) {
      throw new Error(
        `Duplicate message namespace "${namespace}" in ${path.relative(REPO_ROOT, existingFile)} and ${path.relative(REPO_ROOT, filePath)}`,
      );
    }

    knownNamespaces.set(namespace, filePath);
  }
}

function createImportPath(filePath) {
  return path
    .relative(path.dirname(OUTPUT_FILE), filePath)
    .split(path.sep)
    .join("/");
}

async function main() {
  const messageFiles = await collectJsonFiles(SOURCE_ROOT);
  const knownNamespaces = new Map();

  await Promise.all(
    messageFiles.map((filePath) => validateFile(filePath, knownNamespaces)),
  );

  const imports = messageFiles.map((filePath) => {
    const importIdentifier = toImportIdentifier(filePath);
    const importPath = createImportPath(filePath);

    return {
      importIdentifier,
      statement: `import ${importIdentifier} from "${importPath}";`,
    };
  });

  const fileContents = `/**
 * Auto-generated by scripts/generate-intl-types.mjs.
 * Do not edit manually.
 */

${imports.map(({ statement }) => statement).join("\n")}

export const defaultLocaleMessages = {
${imports.map(({ importIdentifier }) => `  ...${importIdentifier},`).join("\n")}
} as const;

export type IntlMessagesSchema = typeof defaultLocaleMessages;
export type IntlNamespace = keyof IntlMessagesSchema;
`;

  await writeFile(OUTPUT_FILE, fileContents);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
